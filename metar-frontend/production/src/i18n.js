  const STORAGE_KEY = 'metar-language';
  const SUPPORTED = Object.freeze(['zh_CN', 'en_US']);
  const valid = (value) => SUPPORTED.includes(value);
  let language = 'zh_CN';
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (valid(saved)) language = saved;
  } catch (_) { /* The language switch also works without browser storage. */ }

  function getLanguage() { return language; }
  function locale() { return language === 'en_US' ? 'en-US' : 'zh-CN'; }
  function setLanguage(value) {
    if (!valid(value)) return false;
    language = value;
    try { window.localStorage.setItem(STORAGE_KEY, value); } catch (_) { /* Keep the current page preference. */ }
    return true;
  }
  function t(key, values = {}) {
    const message = language === 'en_US' && Object.prototype.hasOwnProperty.call(EN, key) ? EN[key] : key;
    return String(message).replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (match, name) => (
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
    ));
  }
  const number = (value) => new Intl.NumberFormat(locale()).format(Number(value) || 0);
  function countLabel(value, kind) {
    const amount = Number(value) || 0;
    const nouns = {
      answers: ['回答', 'answer', 'answers'], questions: ['个问题', 'question', 'questions'],
      views: ['浏览', 'view', 'views'], votes: ['赞同', 'upvote', 'upvotes'],
      bookmarks: ['收藏', 'bookmark', 'bookmarks'], followers: ['关注', 'follower', 'followers'],
    };
    const noun = nouns[kind];
    if (!noun) return number(amount);
    return `${number(amount)} ${language === 'en_US' ? noun[amount === 1 ? 1 : 2] : noun[0]}`;
  }
  function errorMessage(error) {
    if (!error) return '';
    const messages = {
      timeout: '社区服务响应超时，请稍后重试', network: '暂时无法连接社区服务，请稍后重试',
      invalid_response: '社区服务返回了无法识别的数据', inactive: '当前社区账号尚未激活，请先完成 Answer 邮箱验证。',
      unauthorized: '登录状态已过期，请重新登录。',
      binding_unavailable: '绑定状态暂时不可查询，Pulse 页面不会据此猜测身份。',
    };
    if (messages[error.code]) return t(messages[error.code]);
    if (String(error.code || '').startsWith('http_')) return t('社区服务返回 {status}', { status: error.status });
    return error.message ? t(error.message) : '';
  }
  function syncDocument(doc = document) {
    doc.documentElement.lang = locale();
    const skip = doc.querySelector('[data-action="skip"]');
    if (skip) skip.textContent = t('跳到主内容');
    doc.querySelector('meta[name="description"]')?.setAttribute('content', t('METAR 社区：真实问答、知识库与可选 Pulse 权益。'));
  }
  window.MetarI18n = Object.freeze({ getLanguage, locale, setLanguage, t, countLabel, errorMessage, syncDocument });
